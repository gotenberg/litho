func TestGenerate_ProducesValidGo(t *testing.T) {
	dir := findRepoProfilesDir(t)
	allRules, profiles, err := parseProfiles(dir)
	if err != nil {
		t.Fatalf("parseProfiles: %v", err)
	}

	src, err := generate(allRules, profiles)
	if err != nil {
		t.Fatalf("generate: %v", err)
	}
	if len(src) == 0 {
		t.Fatal("generate returned empty buffer")
	}

	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "rules.go", src, parser.ParseComments)
	if err != nil {
		t.Fatalf("generated source does not parse: %v", err)
	}
	if file.Name.Name != "compliance" {
		t.Errorf("package name: got %q, want %q", file.Name.Name, "compliance")
	}

	// Every flavour should have a top-level function declaration.
	srcStr := string(src)
	for _, p := range profiles {
		needle := "func " + p.FuncName + "() []Rule {"
		if !strings.Contains(srcStr, needle) {
			t.Errorf("missing function declaration: %s", p.FuncName)
		}
	}

	if !strings.Contains(srcStr, "// Code generated by cmd/gen-rules; DO NOT EDIT.") {
		t.Error("missing generated-code header")
	}
	if !strings.Contains(srcStr, "type Rule struct {") {
		t.Error("missing Rule struct declaration")
	}
}

func TestGenerate_Deterministic(t *testing.T) {
	dir := findRepoProfilesDir(t)
	allRules, profiles, err := parseProfiles(dir)
	if err != nil {
		t.Fatalf("parseProfiles: %v", err)
	}

	first, err := generate(allRules, profiles)
	if err != nil {
		t.Fatalf("generate (first): %v", err)
	}
	second, err := generate(allRules, profiles)
	if err != nil {
		t.Fatalf("generate (second): %v", err)
	}
	if !bytes.Equal(first, second) {
		t.Error("generate output is not deterministic between runs")
	}
}

// TestGenerate_MatchesCommittedRulesFile pins that the committed rules.go is
// exactly what the generator writes from the vendored profiles. rules.go says
// DO NOT EDIT, and a declaration added to it by hand is lost on the next
// regeneration, so a hand-maintained rule belongs in rules_extra.go.
func TestGenerate_MatchesCommittedRulesFile(t *testing.T) {
	dir := findRepoProfilesDir(t)
	allRules, profiles, err := parseProfiles(dir)
	if err != nil {
		t.Fatalf("parseProfiles: %v", err)
	}
	want, err := generate(allRules, profiles)
	if err != nil {
		t.Fatalf("generate: %v", err)
	}
	got, err := os.ReadFile(filepath.Join("..", "..", "pkg", "internal", "compliance", "rules.go"))
	if err != nil {
		t.Fatalf("reading the committed rules.go: %v", err)
	}
	if !bytes.Equal(got, want) {
		t.Error("rules.go differs from the generator's output: move hand-written rules to rules_extra.go, or run go run ./cmd/gen-rules")
	}
}

func TestMakeVarName(t *testing.T) {
	tests := []struct {
		name string
		key  ruleKey
		want string
	}{
		{
			name: "PDF/A clause with dots",
			key:  ruleKey{Specification: "ISO_19005_1", Clause: "6.1.2", TestNumber: 1},
			want: "Rule_19005_1_6_1_2_t01",
		},
		{
			name: "double-digit test",
			key:  ruleKey{Specification: "ISO_19005_2", Clause: "6.2.3", TestNumber: 12},
			want: "Rule_19005_2_6_2_3_t12",
		},
		{
			name: "single-segment clause",
			key:  ruleKey{Specification: "ISO_14289_1", Clause: "7", TestNumber: 5},
			want: "Rule_14289_1_7_t05",
		},
	}
	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			if got := makeVarName(tc.key); got != tc.want {
				t.Errorf("makeVarName: got %q, want %q", got, tc.want)
			}
		})
	}
}

func TestNormalizeWhitespace(t *testing.T) {
	tests := []struct {
		in, want string
	}{
		{"  hello  world  ", "hello world"},
		{"hello\n\tworld", "hello world"},
		{"   ", ""},
		{"single", "single"},
	}
	for _, tc := range tests {
		if got := normalizeWhitespace(tc.in); got != tc.want {
			t.Errorf("normalizeWhitespace(%q): got %q, want %q", tc.in, got, tc.want)
		}
	}
}

