// findRepoProfilesDir locates the vendored profiles directory by walking
// up from the test working directory. cmd/gen-rules is two levels below
// the repo root.
func findRepoProfilesDir(t *testing.T) string {
	t.Helper()
	candidates := []string{
		filepath.Join("..", "..", "pkg", "internal", "compliance", "profiles"),
	}
	for _, c := range candidates {
		if _, _, err := parseProfiles(c); err == nil {
			return c
		}
	}
	t.Fatalf("could not locate vendored profiles directory")
	return ""
}

func TestParseProfiles_VendoredAllFlavours(t *testing.T) {
	dir := findRepoProfilesDir(t)

	allRules, profiles, err := parseProfiles(dir)
	if err != nil {
		t.Fatalf("parseProfiles: %v", err)
	}

	if got, want := len(profiles), len(profileFiles); got != want {
		t.Errorf("profiles count: got %d, want %d", got, want)
	}
	if len(allRules) == 0 {
		t.Fatal("expected at least one rule across all profiles")
	}

	seen := make(map[string]bool)
	for _, p := range profiles {
		seen[p.Flavour] = true
		if p.FuncName == "" {
			t.Errorf("profile %s has empty FuncName", p.Flavour)
		}
		if len(p.RuleKeys) == 0 {
			t.Errorf("profile %s has zero rules", p.Flavour)
		}
	}
	for _, pf := range profileFiles {
		if !seen[pf.Flavour] {
			t.Errorf("expected profile %s in output", pf.Flavour)
		}
	}
}

