package main

import (
	"archive/zip"
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"time"
)

// The annex the presets come from: ECMA-376 Part 1, 5th edition
// (December 2016), and the digest of the archive the URL served.
const (
	annexURL    = "https://ecma-international.org/wp-content/uploads/ECMA-376-1_5th_edition_december_2016.zip"
	annexSHA256 = "9d0bcad9cf06054785b03762fcfadbf6bab7e54a5f9d69434e34b7fd464d4129"
	stylesZip   = "OfficeOpenXML-SpreadsheetMLStyles.zip"
	presetName  = "presetTableStyles.xml"
	outGoName   = "tablestyles_preset.go"
)

// maxAnnexBytes caps the downloaded archive. Anti-DoS guard for a
// build-time tool, not a format limit: the archive is 43,501,721 bytes.
const maxAnnexBytes = 64 << 20

// maxEntryBytes caps one extracted file: presetTableStyles.xml is 531,457
// bytes. Anti-DoS guard for a build-time tool.
const maxEntryBytes = 8 << 20

// httpClient bounds how long the generator waits for the download.
var httpClient = &http.Client{Timeout: 5 * time.Minute}

func main() {
	src := flag.String("src", "", "local copy of the annex archive, instead of downloading it")
	out := flag.String("out", outGoName, "Go file to write")
	flag.Parse()
	if err := run(*src, *out); err != nil {
		fmt.Fprintln(os.Stderr, "gen-xlsx-tablestyles:", err)
		os.Exit(1)
	}
}

// run reads the annex, extracts the presets and writes the Go file.
func run(src, out string) error {
	annex, err := readAnnex(src)
	if err != nil {
		return err
	}
	sum := sha256.Sum256(annex)
	if got := hex.EncodeToString(sum[:]); got != annexSHA256 {
		return fmt.Errorf("annex digest %s, want %s", got, annexSHA256)
	}
	styles, err := entry(annex, stylesZip)
	if err != nil {
		return err
	}
	preset, err := entry(styles, presetName)
	if err != nil {
		return err
	}
	presets, err := extract(preset)
	if err != nil {
		return err
	}
	code, err := render(presets)
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Clean(out), code, 0o600)
}

// readAnnex returns the annex archive from src, or downloaded.
func readAnnex(src string) ([]byte, error) {
	if src != "" {
		return os.ReadFile(filepath.Clean(src))
	}
	resp, err := httpClient.Get(annexURL)
	if err != nil {
		return nil, fmt.Errorf("downloading the annex: %w", err)
	}
	defer resp.Body.Close() //nolint:errcheck // a read-only response body has nothing to flush
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("downloading the annex: %s", resp.Status)
	}
	data, err := io.ReadAll(io.LimitReader(resp.Body, maxAnnexBytes+1))
	if err != nil {
		return nil, fmt.Errorf("downloading the annex: %w", err)
	}
	if len(data) > maxAnnexBytes {
		return nil, errors.New("the annex is larger than expected")
	}
	return data, nil
}

// entry returns the file name of the zip archive data.
func entry(data []byte, name string) ([]byte, error) {
	zr, err := zip.NewReader(bytes.NewReader(data), int64(len(data)))
	if err != nil {
		return nil, fmt.Errorf("opening the archive holding %s: %w", name, err)
	}
	for _, f := range zr.File {
		if f.Name != name {
			continue
		}
		rc, err := f.Open()
		if err != nil {
			return nil, err
		}
		defer rc.Close() //nolint:errcheck // a read-only zip entry has nothing to flush
		b, err := io.ReadAll(io.LimitReader(rc, maxEntryBytes+1))
		if err != nil {
			return nil, err
		}
		if len(b) > maxEntryBytes {
			return nil, fmt.Errorf("%s is larger than expected", name)
		}
		return b, nil
	}
	return nil, fmt.Errorf("%s not in the archive", name)
}

var (
	spaceRe  = regexp.MustCompile(`>\s+<`)
	presetRe = regexp.MustCompile(`(?s)<(TableStyle\w+)>(.*?)</TableStyle\w+>`)
	countRe  = regexp.MustCompile(` count="\d+"`)
	tablesRe = regexp.MustCompile(`<tableStyles[^>]*>`)
)

// extract returns each TableStyle preset's content, whitespace removed,
// by name.
func extract(xml []byte) (map[string]string, error) {
	s := strings.TrimPrefix(string(xml), "\ufeff")
	s = spaceRe.ReplaceAllString(s, "><")
	out := map[string]string{}
	for _, m := range presetRe.FindAllStringSubmatch(s, -1) {
		body := countRe.ReplaceAllString(m[2], "")
		body = tablesRe.ReplaceAllString(body, "<tableStyles>")
		out[m[1]] = body
	}
	if len(out) == 0 {
		return nil, errors.New("no table style preset found")
	}
	return out, nil
}

// render writes the Go file of the presets.
func render(presets map[string]string) ([]byte, error) {
	names := make([]string, 0, len(presets))
	for n := range presets {
		names = append(names, n)
	}
	sort.Strings(names)
	var b bytes.Buffer
	b.WriteString("// Code generated by cmd/gen-xlsx-tablestyles from ECMA-376 Part 1, 5th edition,\n")
	b.WriteString("// OfficeOpenXML-SpreadsheetMLStyles.zip, " + presetName + ". DO NOT EDIT.\n\n")
	b.WriteString("package xlsx\n\n")
	b.WriteString("// presetTableStyles holds the preset table styles of ECMA-376 Part 1,\n")
	b.WriteString("// 18.8.40, each its dxfs and tableStyles elements, by name.\n")
	b.WriteString("var presetTableStyles = map[string]string{\n")
	for _, n := range names {
		fmt.Fprintf(&b, "\t%q: %q,\n", n, presets[n])
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}
