package main

import (
	"bufio"
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"strings"
	"time"
)

// The data the word list comes from: thaidict.txt of ICU 78.1, which the
// pinned Chromium (156) builds with, and the digest of the file.
const (
	dataURL    = "https://raw.githubusercontent.com/unicode-org/icu/release-78.1/icu4c/source/data/brkitr/dictionaries/thaidict.txt"
	dataSHA256 = "3166abde40c0f44ab91c28f5ce96d7d1472cb7882e1c0bda0a72f8f69dba4274"
	outGoName  = "thai_gen.go"
)

// wantWords is the number of words of the pinned file, which a file
// other than the pinned one would change.
const wantWords = 26383

// thaiBase is the letter one below the Thai block: every word of the list
// is written in it.
const thaiBase = 0x0E00

// maxDataBytes caps the downloaded file. Anti-DoS guard for a build-time
// tool, not a format limit: the file is 493,054 bytes.
const maxDataBytes = 4 << 20

// bytesPerLine is how many bytes of the packed edges one line of the
// generated string holds.
const bytesPerLine = 32

// httpClient bounds how long the generator waits for the download.
var httpClient = &http.Client{Timeout: 5 * time.Minute}

func main() {
	src := flag.String("src", "", "local copy of thaidict.txt, instead of downloading it")
	out := flag.String("out", outGoName, "Go file to write")
	flag.Parse()
	if err := run(*src, *out); err != nil {
		fmt.Fprintln(os.Stderr, "gen-thai-dictionary:", err)
		os.Exit(1)
	}
}

// run reads the file and writes the Go file.
func run(src, out string) error {
	data, err := readData(src)
	if err != nil {
		return err
	}
	sum := sha256.Sum256(data)
	if got := hex.EncodeToString(sum[:]); got != dataSHA256 {
		return fmt.Errorf("file digest %s, want %s", got, dataSHA256)
	}
	notice, words, err := parse(data)
	if err != nil {
		return err
	}
	if len(words) != wantWords {
		return fmt.Errorf("%d words, want %d: %w", len(words), wantWords, errCount)
	}
	edges, err := encode(words, thaiBase)
	if err != nil {
		return err
	}
	code, err := generate(notice, len(words), edges)
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Clean(out), code, 0o600)
}

// errCount reports a file whose words differ in number from the pinned
// one's.
var errCount = errors.New("word count differs from the pinned file")

// readData returns the file from src, or downloaded.
func readData(src string) ([]byte, error) {
	if src != "" {
		return os.ReadFile(filepath.Clean(src))
	}
	resp, err := httpClient.Get(dataURL)
	if err != nil {
		return nil, fmt.Errorf("downloading the file: %w", err)
	}
	defer resp.Body.Close() //nolint:errcheck // a read-only response body has nothing to flush
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("downloading the file: %s", resp.Status)
	}
	data, err := io.ReadAll(io.LimitReader(resp.Body, maxDataBytes+1))
	if err != nil {
		return nil, fmt.Errorf("downloading the file: %w", err)
	}
	if len(data) > maxDataBytes {
		return nil, fmt.Errorf("file past %d bytes", maxDataBytes)
	}
	return data, nil
}

// parse reads the copyright notice, the comment lines that open the file,
// and the words, one a line, the first field of each line that is not a
// comment (ICU's gendict reads a word and an optional value).
func parse(data []byte) (notice []string, words []string, err error) {
	data = bytes.TrimPrefix(data, []byte("\xef\xbb\xbf"))
	sc := bufio.NewScanner(bytes.NewReader(data))
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if c, ok := strings.CutPrefix(line, "#"); ok {
			if len(words) == 0 {
				notice = append(notice, strings.Join(strings.Fields(c), " "))
			}
			continue
		}
		if f := strings.Fields(line); len(f) > 0 {
			words = append(words, f[0])
		}
	}
	if err := sc.Err(); err != nil {
		return nil, nil, err
	}
	if len(notice) == 0 {
		return nil, nil, errors.New("the file holds no copyright notice")
	}
	return notice, words, nil
}

// generate writes the Go source of the word list.
func generate(notice []string, words int, edges string) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by cmd/gen-thai-dictionary from thaidict.txt of ICU 78.1; DO NOT EDIT.\n\n")
	b.WriteString("// The words come from ICU, under this notice and the Unicode License v3\n// (LICENSE-icu):\n//\n")
	for _, l := range notice {
		fmt.Fprintf(&b, "//\t%s\n", l)
	}
	b.WriteString("\npackage dictbreak\n\n")
	b.WriteString("func init() {\n\tthaiWords = &thaiList\n}\n\n")
	b.WriteString("// thaiList is the Thai word list.\nvar thaiList = Dictionary{Base: 0x0E00, Edges: thaiEdges}\n\n")
	fmt.Fprintf(&b, "// thaiEdges are the %d words of the list, packed as %d edges.\n", words, len(edges)/4)
	b.WriteString("const thaiEdges = \"\" +\n")
	for i := 0; i < len(edges); i += bytesPerLine {
		chunk := edges[i:min(i+bytesPerLine, len(edges))]
		b.WriteString("\t\"")
		for j := 0; j < len(chunk); j++ {
			c := chunk[j]
			switch {
			case c == '"' || c == '\\':
				b.WriteByte('\\')
				b.WriteByte(c)
			case c >= 0x20 && c < 0x7f:
				// A hex escape followed by a hex digit stays two
				// characters: \x escapes take exactly two digits.
				b.WriteByte(c)
			default:
				fmt.Fprintf(&b, "\\x%02x", c)
			}
		}
		b.WriteString("\"")
		if i+bytesPerLine < len(edges) {
			b.WriteString(" +")
		}
		b.WriteString("\n")
	}
	return format.Source(b.Bytes())
}
