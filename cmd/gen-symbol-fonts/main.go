package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
	"time"
)

// The source the tables come from: LibreOffice core's fontcvt.cxx at the
// commit the corpora pin, and the digest of the file that commit holds.
const (
	srcURL    = "https://raw.githubusercontent.com/LibreOffice/core/9dea406ab7695df6325b11b0e19fdca8db4b7276/unotools/source/misc/fontcvt.cxx"
	srcSHA256 = "6fec8cd932aebfa2f96697af25eacfaa841f8cae67f7938a7fadf3cd25dc9abe"
	outGoName = "symbols_gen.go"
)

// tableLen is the entries of a recoding table: one per code from 0x20 to
// 0xFF (fontcvt.cxx, ConvertChar::RecodeChar).
const tableLen = 224

// maxSrcBytes caps the downloaded file. Anti-DoS guard for a build-time
// tool, not a format limit: the file is 53,295 bytes.
const maxSrcBytes = 1 << 20

// httpClient bounds how long the generator waits for the download.
var httpClient = &http.Client{Timeout: 5 * time.Minute}

func main() {
	src := flag.String("src", "", "local copy of fontcvt.cxx, instead of downloading it")
	out := flag.String("out", outGoName, "Go file to write")
	flag.Parse()
	if err := run(*src, *out); err != nil {
		fmt.Fprintln(os.Stderr, "gen-symbol-fonts:", err)
		os.Exit(1)
	}
}

// run reads the source and writes the Go file.
func run(src, out string) error {
	data, err := readSrc(src)
	if err != nil {
		return err
	}
	sum := sha256.Sum256(data)
	if got := hex.EncodeToString(sum[:]); got != srcSHA256 {
		return fmt.Errorf("source digest %s, want %s", got, srcSHA256)
	}
	code, err := generate(string(data))
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Clean(out), code, 0o600)
}

// readSrc returns the source from src, or downloaded.
func readSrc(src string) ([]byte, error) {
	if src != "" {
		return os.ReadFile(filepath.Clean(src))
	}
	resp, err := httpClient.Get(srcURL)
	if err != nil {
		return nil, fmt.Errorf("downloading the source: %w", err)
	}
	defer resp.Body.Close() //nolint:errcheck // a read-only response body has nothing to flush
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("downloading the source: %s", resp.Status)
	}
	data, err := io.ReadAll(io.LimitReader(resp.Body, maxSrcBytes+1))
	if err != nil {
		return nil, fmt.Errorf("downloading the source: %w", err)
	}
	if len(data) > maxSrcBytes {
		return nil, errors.New("the source is larger than expected")
	}
	return data, nil
}

var (
	// tableRE matches a recoding table's declaration and body.
	tableRE = regexp.MustCompile(`(?s)const sal_Unicode (a\w+Tab)\[224\]\s*=\s*\{(.*?)\};`)
	// commentRE matches a C++ comment.
	commentRE = regexp.MustCompile(`(?s)//[^\n]*|/\*.*?\*/`)
	// recodeRE matches the StarSymbol recoding list.
	recodeRE = regexp.MustCompile(`(?s)aStarSymbolRecodeTable\[\]\s*=\s*\{(.*?)\n\};`)
	// entryRE matches one entry of the recoding list: a font name and its
	// table.
	entryRE = regexp.MustCompile(`\{"(\w+)",\s*\{(a\w+Tab),`)
)

// generate returns the Go file of the tables of src.
func generate(src string) ([]byte, error) {
	tables := map[string][]uint16{}
	for _, m := range tableRE.FindAllStringSubmatch(src, -1) {
		vals, err := parseTable(m[2])
		if err != nil {
			return nil, fmt.Errorf("table %s: %w", m[1], err)
		}
		tables[m[1]] = vals
	}
	rm := recodeRE.FindStringSubmatch(src)
	if rm == nil {
		return nil, errors.New("no aStarSymbolRecodeTable")
	}
	entries := entryRE.FindAllStringSubmatch(commentRE.ReplaceAllString(rm[1], ""), -1)
	if len(entries) == 0 {
		return nil, errors.New("an empty aStarSymbolRecodeTable")
	}
	var used []string
	seen := map[string]bool{}
	for _, e := range entries {
		if tables[e[2]] == nil {
			return nil, fmt.Errorf("font %s names the unknown table %s", e[1], e[2])
		}
		if !seen[e[2]] {
			seen[e[2]] = true
			used = append(used, e[2])
		}
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by gen-symbol-fonts from LibreOffice core's\n")
	b.WriteString("// unotools/source/misc/fontcvt.cxx (MPL 2.0) at commit\n")
	b.WriteString("// 9dea406ab7695df6325b11b0e19fdca8db4b7276. DO NOT EDIT.\n\n")
	b.WriteString("package slides\n\n")
	b.WriteString("// symbolFonts maps a symbol font's normalized name (lower case, without\n")
	b.WriteString("// spaces) to the OpenSymbol code point of each of its codes from 0x20 to\n")
	b.WriteString("// 0xFF, 0 for a code the table leaves unmapped (fontcvt.cxx,\n")
	b.WriteString("// aStarSymbolRecodeTable).\n")
	b.WriteString("var symbolFonts = map[string]*[224]rune{\n")
	for _, e := range entries {
		fmt.Fprintf(&b, "\t%q: &%s,\n", e[1], goName(e[2]))
	}
	b.WriteString("}\n")
	for _, name := range used {
		fmt.Fprintf(&b, "\n// %s is fontcvt.cxx's %s.\nvar %s = [224]rune{", goName(name), name, goName(name))
		for i, v := range tables[name] {
			if i%8 == 0 {
				b.WriteString("\n\t")
			} else {
				b.WriteString(" ")
			}
			fmt.Fprintf(&b, "0x%04x,", v)
		}
		b.WriteString("\n}\n")
	}
	return format.Source(b.Bytes())
}

// parseTable returns the entries of a table's body, comments removed,
// refusing a body of another length than tableLen.
func parseTable(body string) ([]uint16, error) {
	var vals []uint16
	for f := range strings.SplitSeq(commentRE.ReplaceAllString(body, ""), ",") {
		f = strings.TrimSpace(f)
		if f == "" {
			continue
		}
		v, err := strconv.ParseUint(f, 0, 16)
		if err != nil {
			return nil, err
		}
		vals = append(vals, uint16(v))
	}
	if len(vals) != tableLen {
		return nil, fmt.Errorf("%d entries, want %d", len(vals), tableLen)
	}
	return vals, nil
}

// goName returns the Go name of the table name: aWingDingsTab becomes
// wingDingsTab.
func goName(name string) string {
	s := strings.TrimPrefix(name, "a")
	return strings.ToLower(s[:1]) + s[1:]
}
