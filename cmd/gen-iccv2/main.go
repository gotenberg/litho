package main

import (
	"encoding/binary"
	"flag"
	"fmt"
	"math"
	"os"
	"path/filepath"
)

const outName = "sgray-v2.icc"

// The ICC.1:2001-04 header fields the profile states. version is 2.4.0, the
// version of that edition, the last of version 2.
const (
	version     = 0x02400000
	deviceClass = "mntr"
	colourSpace = "GRAY"
	pcs         = "XYZ "
)

// creationDate is the header's date and time (ICC.1:2001-04, 6.1.4 and
// 5.3.1): a constant, so every run writes the same bytes.
var creationDate = [6]uint16{2026, 10, 19, 0, 0, 0} //nolint:gochecknoglobals // build-time constant.

// pcsIlluminant is the D50 illuminant every profile header names
// (ICC.1:2001-04, 6.1.13).
var pcsIlluminant = [3]float64{0.9642, 1, 0.8249} //nolint:gochecknoglobals // spec constant.

// sRGBWhite is the sRGB reference white, D65 at chromaticity x 0.3127,
// y 0.3290 (IEC 61966-2-1, 3.2), as XYZ with Y = 1. A version 2 display
// profile records the display's white in its media white point
// (ICC.1:2001-04, 6.4.25).
var sRGBWhite = [3]float64{0.3127 / 0.3290, 1, (1 - 0.3127 - 0.3290) / 0.3290} //nolint:gochecknoglobals // spec constant.

// curveEntries is the sample count of the tone curve, the count litho's
// built-in sRGB profile uses for each of its three.
const curveEntries = 1024

// copyright is the text of the copyrightTag (ICC.1:2001-04, 6.4), where a
// profile reader looks for the terms of use. It dedicates the profile to the
// public domain under CC0 1.0, the dedication of the CC0 profile beside it
// (profiles/README.md and profiles/LICENSE), in 7-bit ASCII as textType
// requires.
const copyright = "No copyright, use freely. Dedicated to the public domain under CC0 1.0 " +
	"(https://creativecommons.org/publicdomain/zero/1.0/). " +
	"Generated by litho cmd/gen-iccv2 from IEC 61966-2-1 constants."

const description = "sRGB grey (IEC 61966-2-1 tone curve), litho"

func main() {
	out := flag.String("out", "", "profile directory (default: pkg/internal/graphics/icc/profiles)")
	flag.Parse()

	dir := *out
	if dir == "" {
		dir = findProfileDir()
	}
	if err := os.WriteFile(filepath.Join(dir, outName), generate(), 0o600); err != nil {
		fmt.Fprintf(os.Stderr, "gen-iccv2: writing %s: %v\n", outName, err)
		os.Exit(1)
	}
	fmt.Printf("Generated %s\n", outName)
}

// findProfileDir returns the profile directory of the icc package, from the
// repository root or from the package directory go generate runs in.
func findProfileDir() string {
	for _, dir := range []string{"pkg/internal/graphics/icc/profiles", "profiles"} {
		if info, err := os.Stat(dir); err == nil && info.IsDir() {
			return dir
		}
	}
	fmt.Fprintln(os.Stderr, "gen-iccv2: run from the repository root or pkg/internal/graphics/icc, or pass --out")
	os.Exit(1)
	return ""
}

// srgbToLinear is the sRGB transfer function from a non-linear value to the
// linear one (IEC 61966-2-1, 5.2, equations 1 and 2).
func srgbToLinear(v float64) float64 {
	if v <= 0.04045 {
		return v / 12.92
	}
	return math.Pow((v+0.055)/1.055, 2.4)
}

// generate builds the profile: the header, then the tag table and tags of a
// monochrome display profile (ICC.1:2001-04, 6.3.1.2): profileDescription,
// grayTRC, mediaWhitePoint and copyright.
func generate() []byte {
	trc := binary.BigEndian.AppendUint32([]byte("curv\x00\x00\x00\x00"), curveEntries)
	for i := range curveEntries {
		y := srgbToLinear(float64(i) / (curveEntries - 1))
		trc = binary.BigEndian.AppendUint16(trc, uint16(math.Round(y*65535)))
	}
	tags := []struct {
		sig  string
		data []byte
	}{
		{"desc", textDescription(description)},
		{"kTRC", trc},
		{"wtpt", xyzType(sRGBWhite)},
		{"cprt", textType(copyright)},
	}

	const headerSize = 128
	table := binary.BigEndian.AppendUint32(nil, uint32(len(tags))) //nolint:gosec // four tags.
	offset := headerSize + 4 + 12*len(tags)
	var body []byte
	for _, tag := range tags {
		table = append(table, tag.sig...)
		table = binary.BigEndian.AppendUint32(table, uint32(offset+len(body))) //nolint:gosec // a few kilobytes.
		table = binary.BigEndian.AppendUint32(table, uint32(len(tag.data)))    //nolint:gosec // a few kilobytes.
		body = append(body, tag.data...)
		for len(body)%4 != 0 {
			body = append(body, 0)
		}
	}

	profile := make([]byte, headerSize, headerSize+len(table)+len(body))
	binary.BigEndian.PutUint32(profile[8:], version)
	copy(profile[12:], deviceClass)
	copy(profile[16:], colourSpace)
	copy(profile[20:], pcs)
	for i, v := range creationDate {
		binary.BigEndian.PutUint16(profile[24+2*i:], v)
	}
	copy(profile[36:], "acsp")
	copy(profile[68:], s15(pcsIlluminant[:]...))
	profile = append(append(profile, table...), body...)
	binary.BigEndian.PutUint32(profile, uint32(len(profile))) //nolint:gosec // a few kilobytes.
	return profile
}

// s15 encodes s15Fixed16Numbers (ICC.1:2001-04, 5.3.5).
func s15(vs ...float64) []byte {
	var b []byte
	for _, v := range vs {
		b = binary.BigEndian.AppendUint32(b, uint32(int32(math.Round(v*65536)))) //nolint:gosec // two's complement by definition.
	}
	return b
}

// xyzType builds an XYZType of one value (ICC.1:2001-04, 6.5.26).
func xyzType(v [3]float64) []byte {
	return append([]byte("XYZ \x00\x00\x00\x00"), s15(v[:]...)...)
}

// textType builds a textType (ICC.1:2001-04, 6.5.18): 7-bit ASCII ending in a
// NUL.
func textType(s string) []byte {
	return append(append([]byte("text\x00\x00\x00\x00"), s...), 0)
}

// textDescription builds a textDescriptionType (ICC.1:2001-04, 6.5.17): the
// ASCII description, the same text as Unicode, and an empty ScriptCode
// description of the fixed 67-byte field. The text is ASCII, so each
// character is one UCS-2 unit.
func textDescription(s string) []byte {
	b := []byte("desc\x00\x00\x00\x00")
	b = binary.BigEndian.AppendUint32(b, uint32(len(s)+1)) //nolint:gosec // a constant string.
	b = append(append(b, s...), 0)
	b = binary.BigEndian.AppendUint32(b, 0)
	b = binary.BigEndian.AppendUint32(b, uint32(len(s)+1)) //nolint:gosec // a constant string.
	for _, c := range []byte(s) {
		b = binary.BigEndian.AppendUint16(b, uint16(c))
	}
	b = append(b, 0, 0)
	b = append(b, 0, 0, 0)
	return append(b, make([]byte, 67)...)
}
