package main

import (
	"encoding/binary"
	"errors"
	"fmt"
	"math"
)

// The arithmetic below writes every product that feeds a sum as
// float64(x*y). Go may fuse x*y+z into one rounded operation on some
// architectures (The Go Programming Language Specification, "Floating-point
// operators"), and an explicit conversion forbids it, so the iterative
// separation below rounds alike on every architecture and the committed
// profile matches the generator wherever its test runs.

// errSource reports a CMYK source profile the generator cannot read.
var errSource = errors.New("unexpected CMYK source profile")

// cmykDescription and cmykCopyright are the profile's desc and cprt texts,
// 7-bit ASCII as textDescriptionType and textType require (ICC.1:2001-04,
// 6.5.17 and 6.5.18). The copyright states the CC0 1.0 dedication of the
// generated profile and of the characterisation it reads.
const (
	cmykDescription = "CGATS TR 001 (SWOP) CMYK, litho"
	cmykCopyright   = "No copyright, use freely. Dedicated to the public domain under CC0 1.0 " +
		"(https://creativecommons.org/publicdomain/zero/1.0/). " +
		"Generated by litho cmd/gen-iccv2: AToB tables from the CC0 1.0 profile " +
		"CGATS001Compat-v2-micro of Compact ICC Profiles, BToA tables inverted from them."
)

// b2aGrid is the grid points per Lab axis of the BToA and gamut tables. 17
// points put a node every 6.3 L* and 16 a* or b* units: a nodes-per-axis count
// of the form 2^n+1, as ICC printer tables use, small enough to keep the
// profile near 50 KB, which remediation embeds in every output it gives a
// CMYK intent.
const b2aGrid = 17

// totalInk is the total area coverage the separation keeps to: 300 per cent,
// the SWOP limit of the CGATS TR 001 printing condition the characterisation
// describes.
const totalInk = 3.0

// The separation's black generation: the share of black a neutral of
// normalised darkness d (0 at the paper, 1 at the darkest printable colour)
// prefers is smoothstep((d - blackStart) / (1 - blackStart)), faded out
// linearly by chroma up to blackChroma. It is a medium grey-component
// replacement: highlights print in CMY alone, and black takes over the shadow
// neutrals.
const (
	blackStart  = 0.35
	blackChroma = 60.0
)

// The weights of the separation's least-squares problem, in ΔE*ab units per
// unit of their quantity. blackWeight is small, so colour accuracy always
// wins over the preferred black, which only picks among the CMYK values that
// print one colour; inkWeight is large, so the total area coverage acts as a
// hard limit.
const (
	blackWeight = 0.5
	inkWeight   = 100.0
)

// The solver's budget per node: coarseSteps samples per CMYK axis seed it,
// then at most solverSteps Levenberg-Marquardt steps refine it.
const (
	coarseSteps = 11
	solverSteps = 60
)

// gamutTolerance is the colour difference, in ΔE*ab, past which the gamut
// table marks a Lab node as out of gamut: the separation reaches every
// printable node far closer, so a larger residual is a clipped colour.
const gamutTolerance = 1.0

// lut16 is a parsed lut16Type (ICC.1:2001-04, 6.5.8): normalised input
// curves, a colour lookup table whose first input varies slowest, and output
// curves.
type lut16 struct {
	in, out, grid int
	inCurves      [][]float64
	clut          []float64
	outCurves     [][]float64
}

// generateCMYK builds the CMYK printer profile from source, the CC0
// CGATS001Compat-v2-micro profile: a version 2 output profile (ICC.1:2001-04,
// 6.3.1.3) over the Lab connection space whose AToB tables are source's AToB0
// unchanged and whose BToA tables invert them.
//
// The connection space is Lab because source states its characterisation in
// Lab, so the AToB table carries over byte for byte and the profile reads a
// CMYK colour exactly as litho's built-in DeviceCMYK reading does; and
// because a Lab grid spaces the BToA nodes evenly in perceived colour, where
// an XYZ grid crowds them into the light colours.
//
// An output profile carries an AToB and a BToA table for each of the three
// rendering intents and a gamut table (ICC.1:2001-04, 6.3.1.3). The
// characterisation is colorimetric and its media white is the connection
// space's D50 white, so the three intents share one table each way, and the
// BToA tables clip out-of-gamut colours to the nearest printable one.
func generateCMYK(source []byte) ([]byte, error) {
	a2b, err := findTag(source, "A2B0")
	if err != nil {
		return nil, err
	}
	model, err := parseLut16(a2b)
	if err != nil {
		return nil, err
	}
	if model.in != 4 || model.out != 3 || string(source[16:24]) != "CMYKLab " {
		return nil, fmt.Errorf("%w: %q, AToB0 of %d inputs and %d outputs", errSource, source[16:24], model.in, model.out)
	}
	wtpt, err := findTag(source, "wtpt")
	if err != nil {
		return nil, err
	}

	b2a, gamut := separate(model)
	return assemble("prtr", "CMYK", "Lab ", []tag{
		{sig: "desc", data: textDescription(cmykDescription)},
		{sig: "cprt", data: textType(cmykCopyright)},
		{sig: "wtpt", data: wtpt},
		{sig: "A2B0", data: a2b},
		{sig: "A2B1", same: "A2B0"},
		{sig: "A2B2", same: "A2B0"},
		{sig: "B2A0", data: b2a},
		{sig: "B2A1", same: "B2A0"},
		{sig: "B2A2", same: "B2A0"},
		{sig: "gamt", data: gamut},
	}), nil
}

// findTag returns the data of the tag sig of profile.
func findTag(profile []byte, sig string) ([]byte, error) {
	if len(profile) < 132 {
		return nil, fmt.Errorf("%w: %d bytes", errSource, len(profile))
	}
	count := int(binary.BigEndian.Uint32(profile[128:]))
	for i := range count {
		e := 132 + 12*i
		if e+12 > len(profile) {
			break
		}
		if string(profile[e:e+4]) != sig {
			continue
		}
		off, size := int(binary.BigEndian.Uint32(profile[e+4:])), int(binary.BigEndian.Uint32(profile[e+8:]))
		if off+size > len(profile) || off+size < off {
			return nil, fmt.Errorf("%w: tag %s past the profile", errSource, sig)
		}
		return profile[off : off+size], nil
	}
	return nil, fmt.Errorf("%w: no %s tag", errSource, sig)
}

// parseLut16 reads a lut16Type tag (ICC.1:2001-04, 6.5.8).
func parseLut16(b []byte) (*lut16, error) {
	if len(b) < 52 || string(b[:4]) != "mft2" {
		return nil, fmt.Errorf("%w: AToB0 is not a lut16Type", errSource)
	}
	l := &lut16{in: int(b[8]), out: int(b[9]), grid: int(b[10])}
	inEntries, outEntries := int(binary.BigEndian.Uint16(b[48:])), int(binary.BigEndian.Uint16(b[50:]))
	if l.in < 1 || l.in > 4 || l.out < 1 || l.out > 4 || l.grid < 2 || inEntries < 2 || outEntries < 2 {
		return nil, fmt.Errorf("%w: lut16Type shape", errSource)
	}
	pos := 52
	read := func(n int) ([]float64, error) {
		if pos+2*n > len(b) {
			return nil, fmt.Errorf("%w: lut16Type past its tag", errSource)
		}
		v := make([]float64, n)
		for i := range v {
			v[i] = float64(binary.BigEndian.Uint16(b[pos+2*i:])) / 65535
		}
		pos += 2 * n
		return v, nil
	}
	for range l.in {
		c, err := read(inEntries)
		if err != nil {
			return nil, err
		}
		l.inCurves = append(l.inCurves, c)
	}
	points := 1
	for range l.in {
		points *= l.grid
	}
	var err error
	if l.clut, err = read(points * l.out); err != nil {
		return nil, err
	}
	for range l.out {
		c, err := read(outEntries)
		if err != nil {
			return nil, err
		}
		l.outCurves = append(l.outCurves, c)
	}
	return l, nil
}

// sampleCurve interpolates a sampled curve linearly at v in 0 to 1.
func sampleCurve(c []float64, v float64) float64 {
	x := float64(clamp01(v) * float64(len(c)-1))
	i := min(int(x), len(c)-2)
	f := x - float64(i)
	return c[i] + float64(f*(c[i+1]-c[i]))
}

func clamp01(v float64) float64 {
	return math.Min(1, math.Max(0, v))
}

// eval runs the table on the normalised inputs and returns its normalised
// outputs, interpolating as litho's colour engine and LittleCMS do:
// tetrahedrally over the last three inputs, and linearly along any before.
func (l *lut16) eval(x []float64) [4]float64 {
	var in [4]float64
	for i := range l.in {
		in[i] = sampleCurve(l.inCurves[i], x[i])
	}
	var out [4]float64
	l.interp(in[:l.in], 0, 0, 1, &out)
	for k := range l.out {
		out[k] = sampleCurve(l.outCurves[k], out[k])
	}
	return out
}

// stride returns the offset between neighbouring grid points along dim.
func (l *lut16) stride(dim int) int {
	s := l.out
	for d := dim + 1; d < l.in; d++ {
		s *= l.grid
	}
	return s
}

// cell returns the grid cell v falls in and its fraction across it.
func (l *lut16) cell(v float64) (int, float64) {
	x := float64(clamp01(v) * float64(l.grid-1))
	i := min(int(x), l.grid-2)
	return i, x - float64(i)
}

// interp adds weight times the table's value over the inputs from dim on, at
// offset base, to out.
func (l *lut16) interp(in []float64, dim, base int, weight float64, out *[4]float64) {
	if l.in-dim == 3 {
		l.tetrahedral(in[dim:], base, weight, out)
		return
	}
	i, f := l.cell(in[dim])
	s := l.stride(dim)
	l.interp(in, dim+1, base+i*s, float64(weight*(1-f)), out)
	if f > 0 {
		l.interp(in, dim+1, base+(i+1)*s, float64(weight*f), out)
	}
}

// tetrahedral interpolates over the last three inputs from base, splitting
// the cell into the six tetrahedra LittleCMS uses.
func (l *lut16) tetrahedral(in []float64, base int, weight float64, out *[4]float64) {
	x, rx := l.cell(in[0])
	y, ry := l.cell(in[1])
	z, rz := l.cell(in[2])
	sx, sy, sz := l.stride(l.in-3), l.stride(l.in-2), l.stride(l.in-1)
	o := base + x*sx + y*sy + z*sz
	at := func(dx, dy, dz, k int) float64 { return l.clut[o+dx*sx+dy*sy+dz*sz+k] }
	// Each case walks from the cell's origin to its far corner along the axes
	// in decreasing order of their fraction.
	type step struct {
		f          float64
		dx, dy, dz int
	}
	var path [3]step
	switch {
	case rx >= ry && ry >= rz:
		path = [3]step{{rx, 1, 0, 0}, {ry, 1, 1, 0}, {rz, 1, 1, 1}}
	case rx >= rz && rz >= ry:
		path = [3]step{{rx, 1, 0, 0}, {rz, 1, 0, 1}, {ry, 1, 1, 1}}
	case rz >= rx && rx >= ry:
		path = [3]step{{rz, 0, 0, 1}, {rx, 1, 0, 1}, {ry, 1, 1, 1}}
	case ry >= rx && rx >= rz:
		path = [3]step{{ry, 0, 1, 0}, {rx, 1, 1, 0}, {rz, 1, 1, 1}}
	case ry >= rz && rz >= rx:
		path = [3]step{{ry, 0, 1, 0}, {rz, 0, 1, 1}, {rx, 1, 1, 1}}
	default:
		path = [3]step{{rz, 0, 0, 1}, {ry, 0, 1, 1}, {rx, 1, 1, 1}}
	}
	for k := range l.out {
		prev := at(0, 0, 0, k)
		v := prev
		for _, s := range path {
			next := at(s.dx, s.dy, s.dz, k)
			v += float64(s.f * (next - prev))
			prev = next
		}
		out[k] += float64(weight * v)
	}
}

// Legacy 16-bit Lab of a version 2 lut16Type (ICC.1:2001-04, 6.5.8): L* 100
// is 0xFF00 and a* or b* 0 is 0x8000, in steps of 1/256.
const (
	lScale  = 100 * 65535.0 / 65280
	abScale = 65535.0 / 256
)

// toLab decodes normalised legacy 16-bit Lab.
func toLab(v [4]float64) [3]float64 {
	return [3]float64{float64(v[0] * lScale), float64(v[1]*abScale) - 128, float64(v[2]*abScale) - 128}
}

// separator inverts a CMYK to Lab characterisation.
type separator struct {
	model        *lut16
	seeds        [][2][4]float64 // CMYK and its Lab, the first three Lab entries
	paper, black float64         // L* of the paper and of the darkest seed
}

func newSeparator(model *lut16) *separator {
	s := &separator{model: model, black: math.Inf(1)}
	for i := range coarseSteps * coarseSteps * coarseSteps * coarseSteps {
		var x [4]float64
		n := i
		for d := 3; d >= 0; d-- {
			x[d] = float64(n%coarseSteps) / (coarseSteps - 1)
			n /= coarseSteps
		}
		if x[0]+x[1]+x[2]+x[3] > totalInk+1e-9 {
			continue
		}
		lab := s.lab(x)
		s.seeds = append(s.seeds, [2][4]float64{x, {lab[0], lab[1], lab[2]}})
		s.black = math.Min(s.black, lab[0])
	}
	s.paper = s.lab([4]float64{})[0]
	return s
}

// lab returns the Lab colour the characterisation prints CMYK x as.
func (s *separator) lab(x [4]float64) [3]float64 {
	return toLab(s.model.eval(x[:]))
}

// preferredBlack returns the share of black the black generation asks of the
// Lab colour t.
func (s *separator) preferredBlack(t [3]float64) float64 {
	d := clamp01((s.paper - t[0]) / (s.paper - s.black))
	r := clamp01((d - blackStart) / (1 - blackStart))
	chroma := math.Sqrt(float64(t[1]*t[1]) + float64(t[2]*t[2]))
	return float64(float64(r*r)*(3-float64(2*r))) * clamp01(1-chroma/blackChroma)
}

// residuals returns the least-squares residuals of CMYK x for the Lab target
// t and preferred black k: the Lab error, the black deviation and the total
// area coverage past its limit, each weighted.
func (s *separator) residuals(x [4]float64, t [3]float64, k float64) [5]float64 {
	lab := s.lab(x)
	return [5]float64{
		lab[0] - t[0], lab[1] - t[1], lab[2] - t[2],
		float64(blackWeight * (x[3] - k)),
		float64(inkWeight * math.Max(0, x[0]+x[1]+x[2]+x[3]-totalInk)),
	}
}

func sumSquares(r [5]float64) float64 {
	var c float64
	for _, v := range r {
		c += float64(v * v)
	}
	return c
}

// separate returns the BToA table and the gamut table over a b2aGrid Lab
// grid: for each node, the CMYK whose colour is nearest it within the total
// area coverage, with the preferred black among the CMYK values that print
// that colour.
func separate(model *lut16) (b2a, gamut []byte) {
	s := newSeparator(model)
	nodes := b2aGrid * b2aGrid * b2aGrid
	cmyk := make([]uint16, 0, 4*nodes)
	outOfGamut := make([]uint16, 0, nodes)
	for i := range nodes {
		n := [3]float64{
			float64(i/(b2aGrid*b2aGrid)) / (b2aGrid - 1),
			float64(i/b2aGrid%b2aGrid) / (b2aGrid - 1),
			float64(i%b2aGrid) / (b2aGrid - 1),
		}
		t := toLab([4]float64{n[0], n[1], n[2]})
		x, dE := s.solve(t)
		for _, v := range x {
			cmyk = append(cmyk, uint16(math.Round(v*65535)))
		}
		// Per ICC.1:2001-04, 6.4.20, 0 marks a colour in gamut and any other
		// value one out of it.
		var flag uint16
		if dE > gamutTolerance {
			flag = 65535
		}
		outOfGamut = append(outOfGamut, flag)
	}
	return lut16Type(3, 4, b2aGrid, cmyk), lut16Type(3, 1, b2aGrid, outOfGamut)
}

// solve separates the Lab colour t: it seeds from the coarse sample of least
// cost, then refines by projected Levenberg-Marquardt steps inside the CMYK
// cube. It returns the CMYK and its colour difference from t in ΔE*ab.
func (s *separator) solve(t [3]float64) ([4]float64, float64) {
	k := s.preferredBlack(t)
	var x [4]float64
	best := math.Inf(1)
	for _, seed := range s.seeds {
		lab := seed[1]
		dl, da, db := lab[0]-t[0], lab[1]-t[1], lab[2]-t[2]
		dk := float64(blackWeight * (seed[0][3] - k))
		c := float64(dl*dl) + float64(da*da) + float64(db*db) + float64(dk*dk)
		if c < best {
			best, x = c, seed[0]
		}
	}

	const h = 1e-4
	r := s.residuals(x, t, k)
	cost := sumSquares(r)
	mu := 1e-3
	for range solverSteps {
		var jac [5][4]float64
		for j := range 4 {
			xh, step := x, h
			if xh[j]+step > 1 {
				step = -h
			}
			xh[j] += step
			rh := s.residuals(xh, t, k)
			for i := range 5 {
				jac[i][j] = (rh[i] - r[i]) / step
			}
		}
		var a [4][5]float64
		for p := range 4 {
			for q := range 4 {
				for i := range 5 {
					a[p][q] += float64(jac[i][p] * jac[i][q])
				}
			}
			a[p][p] += mu
			for i := range 5 {
				a[p][4] -= float64(jac[i][p] * r[i])
			}
		}
		delta, ok := solve4(a)
		if !ok {
			break
		}
		var next [4]float64
		for j := range 4 {
			next[j] = clamp01(x[j] + delta[j])
		}
		nr := s.residuals(next, t, k)
		if nc := sumSquares(nr); nc < cost {
			x, r, cost = next, nr, nc
			mu = math.Max(mu/3, 1e-9)
			continue
		}
		mu *= 4
		if mu > 1e6 {
			break
		}
	}
	return x, math.Sqrt(float64(r[0]*r[0]) + float64(r[1]*r[1]) + float64(r[2]*r[2]))
}

// solve4 solves the 4 by 4 system of the augmented matrix a by Gaussian
// elimination with partial pivoting, reporting false when it is singular.
func solve4(a [4][5]float64) ([4]float64, bool) {
	for c := range 4 {
		p := c
		for r := c + 1; r < 4; r++ {
			if math.Abs(a[r][c]) > math.Abs(a[p][c]) {
				p = r
			}
		}
		if a[p][c] == 0 {
			return [4]float64{}, false
		}
		a[c], a[p] = a[p], a[c]
		for r := c + 1; r < 4; r++ {
			f := a[r][c] / a[c][c]
			for q := c; q < 5; q++ {
				a[r][q] -= float64(f * a[c][q])
			}
		}
	}
	var x [4]float64
	for r := 3; r >= 0; r-- {
		v := a[r][4]
		for q := r + 1; q < 4; q++ {
			v -= float64(a[r][q] * x[q])
		}
		x[r] = v / a[r][r]
	}
	return x, true
}

// lut16Type builds a lut16Type (ICC.1:2001-04, 6.5.8) of in inputs and out
// outputs over a grid of grid points per input: an identity matrix, identity
// input and output curves of two entries, and the table, first input varying
// slowest.
func lut16Type(in, out, grid int, table []uint16) []byte {
	b := []byte("mft2\x00\x00\x00\x00")
	b = append(b, byte(in), byte(out), byte(grid), 0) //nolint:gosec // at most 4 channels and 17 points.
	b = append(b, s15(1, 0, 0, 0, 1, 0, 0, 0, 1)...)
	b = binary.BigEndian.AppendUint16(b, 2)
	b = binary.BigEndian.AppendUint16(b, 2)
	for range in {
		b = binary.BigEndian.AppendUint16(binary.BigEndian.AppendUint16(b, 0), 65535)
	}
	for _, v := range table {
		b = binary.BigEndian.AppendUint16(b, v)
	}
	for range out {
		b = binary.BigEndian.AppendUint16(binary.BigEndian.AppendUint16(b, 0), 65535)
	}
	return b
}
