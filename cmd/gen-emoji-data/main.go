package main

import (
	"bufio"
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"
	"time"
	"unicode"
)

// The emoji data the properties come from: emoji-data.txt of Unicode
// 17.0, the version ICU 78 carries, which the pinned Chromium (156)
// builds with, and the digest of the file.
const (
	dataURL    = "https://www.unicode.org/Public/17.0.0/ucd/emoji/emoji-data.txt"
	dataSHA256 = "2cb2bb9455cda83e8481541ecf5b6dfda66a3bb89efa3fa7c5297eccf607b72b"
	outGoName  = "emoji_gen.go"
)

// maxDataBytes caps the downloaded file. Anti-DoS guard for a build-time
// tool, not a format limit: the file is 107,325 bytes.
const maxDataBytes = 4 << 20

// httpClient bounds how long the generator waits for the download.
var httpClient = &http.Client{Timeout: 5 * time.Minute}

// properties are the properties written, each with the Go name of its
// table and the count of ranges the file lists for it, which a file other
// than the pinned one would change.
var properties = []struct {
	name, table string
	ranges      int
}{
	{"Emoji", "emojiChars", 151},
	{"Emoji_Presentation", "emojiPresentation", 81},
	{"Emoji_Modifier", "emojiModifier", 1},
	{"Emoji_Modifier_Base", "emojiModifierBase", 40},
	{"Extended_Pictographic", "extendedPictographic", 156},
}

func main() {
	src := flag.String("src", "", "local copy of emoji-data.txt, instead of downloading it")
	out := flag.String("out", outGoName, "Go file to write")
	flag.Parse()
	if err := run(*src, *out); err != nil {
		fmt.Fprintln(os.Stderr, "gen-emoji-data:", err)
		os.Exit(1)
	}
}

// run reads the file and writes the Go file.
func run(src, out string) error {
	data, err := readData(src)
	if err != nil {
		return err
	}
	sum := sha256.Sum256(data)
	if got := hex.EncodeToString(sum[:]); got != dataSHA256 {
		return fmt.Errorf("file digest %s, want %s", got, dataSHA256)
	}
	props, err := parse(data)
	if err != nil {
		return err
	}
	code, err := generate(props)
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Clean(out), code, 0o600)
}

// readData returns the file from src, or downloaded.
func readData(src string) ([]byte, error) {
	if src != "" {
		return os.ReadFile(filepath.Clean(src))
	}
	resp, err := httpClient.Get(dataURL)
	if err != nil {
		return nil, fmt.Errorf("downloading the file: %w", err)
	}
	defer resp.Body.Close() //nolint:errcheck // a read-only response body has nothing to flush
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("downloading the file: %s", resp.Status)
	}
	data, err := io.ReadAll(io.LimitReader(resp.Body, maxDataBytes+1))
	if err != nil {
		return nil, fmt.Errorf("downloading the file: %w", err)
	}
	if len(data) > maxDataBytes {
		return nil, fmt.Errorf("file past %d bytes", maxDataBytes)
	}
	return data, nil
}

// span is a range of code points, both ends included.
type span struct{ lo, hi rune }

// parse reads the ranges of each property the file lists (UTS #51, Annex
// A: "<codepoint(s)> ; <property> # <comments>").
func parse(data []byte) (map[string][]span, error) {
	props := map[string][]span{}
	sc := bufio.NewScanner(bytes.NewReader(data))
	for sc.Scan() {
		line, _, _ := strings.Cut(sc.Text(), "#")
		cps, prop, ok := strings.Cut(line, ";")
		if !ok {
			continue
		}
		prop = strings.TrimSpace(prop)
		loText, hiText, isRange := strings.Cut(strings.TrimSpace(cps), "..")
		lo, err := strconv.ParseUint(loText, 16, 32)
		if err != nil {
			return nil, fmt.Errorf("code point %q: %w", loText, err)
		}
		hi := lo
		if isRange {
			if hi, err = strconv.ParseUint(hiText, 16, 32); err != nil {
				return nil, fmt.Errorf("code point %q: %w", hiText, err)
			}
		}
		props[prop] = append(props[prop], span{rune(lo), rune(hi)})
	}
	if err := sc.Err(); err != nil {
		return nil, err
	}
	for _, p := range properties {
		got := merge(props[p.name])
		if len(got) == 0 {
			return nil, fmt.Errorf("no %s range", p.name)
		}
		props[p.name] = got
	}
	return props, nil
}

// merge sorts spans and joins those that touch.
func merge(spans []span) []span {
	slices.SortFunc(spans, func(a, b span) int { return int(a.lo - b.lo) })
	var out []span
	for _, s := range spans {
		if n := len(out); n > 0 && s.lo <= out[n-1].hi+1 {
			out[n-1].hi = max(out[n-1].hi, s.hi)
			continue
		}
		out = append(out, s)
	}
	return out
}

// errCount reports a file whose ranges differ in number from the pinned
// one's.
var errCount = errors.New("range count differs from the pinned file")

// generate writes the Go source of the tables.
func generate(props map[string][]span) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(`// Code generated by cmd/gen-emoji-data from emoji-data.txt of Unicode 17.0; DO NOT EDIT.

// © 2025 Unicode®, Inc. Unicode and the Unicode Logo are registered
// trademarks of Unicode, Inc. in the U.S. and other countries. Distributed
// under the Unicode License v3: https://www.unicode.org/license.txt

package text

import "unicode"

`)
	for _, p := range properties {
		spans := props[p.name]
		if len(spans) != p.ranges {
			return nil, fmt.Errorf("%s: %d ranges, want %d: %w", p.name, len(spans), p.ranges, errCount)
		}
		fmt.Fprintf(&b, "// %s holds the characters of the %s property (UTS #51, Annex A).\n", p.table, p.name)
		fmt.Fprintf(&b, "var %s = &unicode.RangeTable{\n", p.table)
		var r16, r32 []span
		latin := 0
		for _, s := range spans {
			switch {
			case s.hi <= 0xFFFF:
				r16 = append(r16, s)
				if s.hi <= unicode.MaxLatin1 {
					latin++
				}
			case s.lo > 0xFFFF:
				r32 = append(r32, s)
			default:
				r16 = append(r16, span{s.lo, 0xFFFF})
				r32 = append(r32, span{0x10000, s.hi})
			}
		}
		if len(r16) > 0 {
			b.WriteString("\tR16: []unicode.Range16{\n")
			for _, s := range r16 {
				fmt.Fprintf(&b, "\t\t{Lo: 0x%04X, Hi: 0x%04X, Stride: 1},\n", s.lo, s.hi)
			}
			b.WriteString("\t},\n")
		}
		if len(r32) > 0 {
			b.WriteString("\tR32: []unicode.Range32{\n")
			for _, s := range r32 {
				fmt.Fprintf(&b, "\t\t{Lo: 0x%X, Hi: 0x%X, Stride: 1},\n", s.lo, s.hi)
			}
			b.WriteString("\t},\n")
		}
		if latin > 0 {
			fmt.Fprintf(&b, "\tLatinOffset: %d,\n", latin)
		}
		b.WriteString("}\n\n")
	}
	return format.Source(b.Bytes())
}
