// codeOrder names the format codes of a locale in the order of numfmt's
// code constants (pkg/internal/numfmt/locale.go): a formatindex, a usage
// whose default format it is, or "currency" and "currencyInt", the default
// currency's formats.
var codeOrder = []string{
	"7", "8", "9", "12", "13", "14", "15", "18", "19", "20", "21", "33", "39", "40", "41", "42", "43", "44", "45",
	"46", "47", "50", "DATE", "TIME", "DATE_TIME", "PERCENT_NUMBER", "SCIENTIFIC_NUMBER", "currency", "currencyInt",
}

// header is the first lines of both generated files.
const header = `// Code generated by gen-locales from LibreOffice core's
// i18npool/source/localedata/data, i18nlangtag/source/isolang/isolang.cxx
// and include/i18nlangtag/lang.h (MPL 2.0) at commit
// ` + commit + `. DO NOT EDIT.
`

// generate writes the numfmt table and the models constants from the
// extract.
func generate(data []byte) ([]byte, []byte, error) {
	var x extractFile
	if err := json.Unmarshal(data, &x); err != nil {
		return nil, nil, err
	}
	if x.Commit != commit {
		return nil, nil, fmt.Errorf("extract of commit %s, want %s", x.Commit, commit)
	}
	locs := slices.Clone(x.Locales)
	slices.SortFunc(locs, func(a, b localeRecord) int { return strings.Compare(a.Tag, b.Tag) })
	for i := 1; i < len(locs); i++ {
		if locs[i].Tag == locs[i-1].Tag {
			return nil, nil, fmt.Errorf("two locales %s", locs[i].Tag)
		}
	}
	table, err := emitTable(locs)
	if err != nil {
		return nil, nil, err
	}
	models, err := emitModels(locs)
	if err != nil {
		return nil, nil, err
	}
	return table, models, nil
}

// constName returns the Go name of a tag's constant: ca-ES-valencia gives
// LocaleCaESValencia, sr-Latn-RS LocaleSrLatnRS.
func constName(tag string) string {
	var b strings.Builder
	b.WriteString("Locale")
	for i, part := range strings.Split(tag, "-") {
		switch {
		case i > 0 && (len(part) == 2 || len(part) == 3 && part[0] >= '0' && part[0] <= '9'):
			b.WriteString(strings.ToUpper(part))
		default:
			b.WriteString(strings.ToUpper(part[:1]) + strings.ToLower(part[1:]))
		}
	}
	return b.String()
}

// emitModels writes pkg/models/locale_gen.go.
func emitModels(locs []localeRecord) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString("\npackage models\n\n")
	b.WriteString("// The locales a conversion formats spreadsheet values under, one a locale\n// LibreOffice ships, named by its BCP 47 tag.\nconst (\n")
	for _, l := range locs {
		name := l.Language
		if l.Country != "" {
			name += " (" + l.Country + ")"
		}
		fmt.Fprintf(&b, "\t// %s is %s.\n\t%s Locale = %q\n", constName(l.Tag), name, constName(l.Tag), l.Tag)
	}
	b.WriteString(")\n")
	return format.Source(b.Bytes())
}

// pool writes each distinct value once as a package variable and returns
// its name.
type pool struct {
	prefix string
	names  map[string]string
	decls  []string
}

// ref returns the variable holding the Go literal lit, declaring it the
// first time.
func (p *pool) ref(lit string) string {
	if n, ok := p.names[lit]; ok {
		return n
	}
	n := p.prefix + strconv.Itoa(len(p.decls))
	p.names[lit] = n
	p.decls = append(p.decls, fmt.Sprintf("%s = %s", n, lit))
	return n
}

// namesLit returns a Go literal of a list of name pairs.
func namesLit(typ string, pairs [][2]string) string {
	var b strings.Builder
	b.WriteString(typ + "{")
	for i, p := range pairs {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(&b, "{%q, %q}", p[0], p[1])
	}
	b.WriteString("}")
	return b.String()
}

// currencyCode returns the format code of the locale's default currency:
// the code of formatindex base, its currency symbol replaced by the
// default currency's and its decimals by that currency's, as LibreOffice
// builds the default currency format (svl zforlist.cxx,
// SvNumberFormatter::GetCurrencyFormatStrings).
func currencyCode(l localeRecord, base string, decimals int) string {
	code := l.Codes[base]
	if code == "" {
		return ""
	}
	var b strings.Builder
	for len(code) > 0 {
		i := strings.Index(code, "[$")
		if i < 0 {
			b.WriteString(code)
			break
		}
		b.WriteString(code[:i])
		j := strings.IndexByte(code[i:], ']')
		if j < 0 {
			b.WriteString(code[i:])
			break
		}
		tag := code[i+2 : i+j]
		if k := strings.LastIndexByte(tag, '-'); k >= 0 {
			tag = l.Currency + tag[k:]
		}
		b.WriteString("[$" + tag + "]")
		code = code[i+j+1:]
	}
	digits := "#,##0"
	if decimals > 0 {
		digits += "." + strings.Repeat("0", decimals)
	}
	return numberPart.ReplaceAllLiteralString(b.String(), digits)
}

// numberPart matches the number of a currency format code: grouped
// digits and their decimals.
var numberPart = regexp.MustCompile(`#,##0(\.0+)?`)

// codesOf returns the codes of a locale in codeOrder.
func codesOf(l localeRecord) []string {
	out := make([]string, len(codeOrder))
	for i, k := range codeOrder {
		switch k {
		case "currency":
			out[i] = currencyCode(l, "13", l.CurrencyDigits)
		case "currencyInt":
			out[i] = currencyCode(l, "12", 0)
		default:
			out[i] = l.Codes[k]
		}
	}
	return out
}

// emitTable writes pkg/internal/numfmt/locale_gen.go.
func emitTable(locs []localeRecord) ([]byte, error) {
	names := &pool{prefix: "names", names: map[string]string{}}
	codes := &pool{prefix: "codes", names: map[string]string{}}
	var rows strings.Builder
	var lcidRows []string
	for i, l := range locs {
		if len(l.LCIDs) == 0 {
			return nil, fmt.Errorf("%s: no Windows locale identifier", l.Tag)
		}
		months := names.ref(namesLit("[12][2]string", l.Months[:]))
		days := names.ref(namesLit("[7][2]string", l.Days[:]))
		genitive := "nil"
		if l.Genitive != nil {
			genitive = "&" + names.ref(namesLit("[12][2]string", l.Genitive[:]))
		}
		partitive := "nil"
		if l.Partitive != nil {
			partitive = "&" + names.ref(namesLit("[12][2]string", l.Partitive[:]))
		}
		narrow := "nil"
		if l.Narrow != nil {
			var q []string
			for _, n := range l.Narrow {
				q = append(q, strconv.Quote(n))
			}
			narrow = "&" + names.ref("[12]string{"+strings.Join(q, ", ")+"}")
		}
		cs := codesOf(l)
		var cl strings.Builder
		cl.WriteString("[numCodes]string{")
		for k, c := range cs {
			if k > 0 {
				cl.WriteString(", ")
			}
			cl.WriteString(strconv.Quote(c))
		}
		cl.WriteString("}")
		code := codes.ref(cl.String())
		fmt.Fprintf(&rows, "\t{tag: models.%s, lcid: 0x%04X, decimal: %q, decimalAlt: %q, group: %q, dateSep: %q, timeSep: %q, time100Sep: %q, am: %q, pm: %q, trueWord: %q, falseWord: %q, indian: %v, currency: %q, calendar: %q, months: &%s, genitive: %s, partitive: %s, narrow: %s, days: &%s, codes: &%s, acceptance: %s},\n",
			constName(l.Tag), l.LCIDs[0], l.Decimal, l.DecimalAlt, l.Group, l.DateSep, l.TimeSep, l.Time100Sep, l.AM, l.PM,
			l.True, l.False, slices.Equal(l.Grouping, []int{3, 2}), l.Currency, l.Calendar, months, genitive, partitive, narrow, days, code, stringsLit(l.Acceptance))
		for _, id := range l.LCIDs {
			lcidRows = append(lcidRows, fmt.Sprintf("{0x%04X, %d}", id, i))
		}
	}
	// One identifier names one locale: the first that claims it.
	slices.SortStableFunc(lcidRows, func(a, b string) int { return strings.Compare(a[:8], b[:8]) })
	lcidRows = slices.CompactFunc(lcidRows, func(a, b string) bool { return a[:8] == b[:8] })
	if len(locs) > 1<<16 {
		return nil, errors.New("too many locales")
	}
	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString("\npackage numfmt\n\nimport \"github.com/gotenberg/litho/pkg/models\"\n\n")
	b.WriteString("// locales are the locales of models' Locale constants, sorted by tag.\nvar locales = [...]localeData{\n")
	b.WriteString(rows.String())
	b.WriteString("}\n\n")
	b.WriteString("// lcidLocales map a Windows locale identifier to its locale, an index of\n// locales, sorted by identifier.\nvar lcidLocales = [...]lcidLocale{\n")
	for _, r := range lcidRows {
		b.WriteString("\t" + r + ",\n")
	}
	b.WriteString("}\n\n")
	b.WriteString("// The names and codes the locales share.\nvar (\n")
	for _, d := range names.decls {
		b.WriteString("\t" + d + "\n")
	}
	for _, d := range codes.decls {
		b.WriteString("\t" + d + "\n")
	}
	b.WriteString(")\n")
	return format.Source(b.Bytes())
}

// stringsLit returns a Go literal of a string slice, nil for none.
func stringsLit(s []string) string {
	if len(s) == 0 {
		return "nil"
	}
	q := make([]string, len(s))
	for i, v := range s {
		q[i] = strconv.Quote(v)
	}
	return "[]string{" + strings.Join(q, ", ") + "}"
}
