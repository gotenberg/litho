// sampleJS mirrors the layout of PDF.js's standard_fonts.js, including the
// wrapped "getLookupTableFactory(\n  function (t) {" form prettier gives some
// tables.
const sampleJS = `/* Copyright 2015 Mozilla Foundation
 */

const getGlyphMapForStandardFonts = getLookupTableFactory(function (t) {
  t[2] = 10;
  t[3] = 32;
  // A comment line.

  t[4] = 33;
});

const getSupplementalGlyphMapForArialBlack = getLookupTableFactory(
  function (t) {
    t[227] = 322;
  }
);

const getSupplementalGlyphMapForCalibri = getLookupTableFactory(function (t) {
  t[1] = 32;
  t[4] = 65;
  t[1004] = 48;
});

const getStdFontMap = getLookupTableFactory(function (t) {
  // The standard 14 fonts:
  t["Times-Roman"] = "Times-Roman";
  t.Helvetica = "Helvetica";
  t.Arial = "Helvetica";
});

const getNonStdFontMap = getLookupTableFactory(function (t) {
  t.Calibri = "Helvetica";
  t["MS-Gothic"] = "MS Gothic";
});

const getSerifFonts = getLookupTableFactory(function (t) {
  t["Adobe Jenson"] = true;
  t.Albertus = true;
});

const getSymbolsFonts = getLookupTableFactory(function (t) {
  t.Symbol = true;
});
`

func TestParseLookupTable(t *testing.T) {
	t.Parallel()

	got, err := parseLookupTable(sampleJS, "getSupplementalGlyphMapForCalibri")
	if err != nil {
		t.Fatalf("parseLookupTable: %v", err)
	}
	want := map[uint16]rune{1: ' ', 4: 'A', 1004: '0'}
	if len(got) != len(want) {
		t.Fatalf("got %d entries %v, want %v", len(got), got, want)
	}
	for gid, r := range want {
		if got[gid] != r {
			t.Errorf("GID %d = %q, want %q", gid, got[gid], r)
		}
	}

	wrapped, err := parseLookupTable(sampleJS, "getSupplementalGlyphMapForArialBlack")
	if err != nil || wrapped[227] != 322 || len(wrapped) != 1 {
		t.Errorf("wrapped table = %v (err %v), want {227: 322}", wrapped, err)
	}
}

// TestParseLookupTableRefusesWhatItCannotTranscribe pins that the parser
// fails rather than emit a partial or wrong table.
func TestParseLookupTableRefusesWhatItCannotTranscribe(t *testing.T) {
	t.Parallel()

	table := func(body string) string {
		return "const getX = getLookupTableFactory(function (t) {\n" + body + "\n});\n"
	}
	for _, tc := range []struct {
		desc string
		js   string
		want error
	}{
		{"absent", sampleJS, errTableNotFound},
		{"empty", table("  // nothing"), errTableNotFound},
		{"loop", table("  for (let i = 0; i < 9; i++) {\n    t[i] = i;\n  }"), errUnexpectedStmt},
		{"computed value", table("  t[3] = 0x20;"), errUnexpectedStmt},
		{"glyph ID past 16 bits", table("  t[65536] = 32;"), errEntryRange},
		{"surrogate", table("  t[3] = 55296;"), errEntryRange},
		{"past U+10FFFF", table("  t[3] = 1114112;"), errEntryRange},
		{"duplicate", table("  t[3] = 32;\n  t[3] = 33;"), errDuplicateEntry},
	} {
		if _, err := parseLookupTable(tc.js, "getX"); !errors.Is(err, tc.want) {
			t.Errorf("%s: err = %v, want %v", tc.desc, err, tc.want)
		}
	}
}

// TestGenerate pins that the output is Go that parses, carries the
// generated-code marker and the attribution, and holds every table.
func TestGenerate(t *testing.T) {
	t.Parallel()

	code, err := generate(sampleJS)
	if err != nil {
		t.Fatalf("generate: %v", err)
	}
	src := string(code)
	if !strings.HasPrefix(src, "// Code generated by cmd/gen-stdfonts; DO NOT EDIT.\n") {
		t.Errorf("missing the generated-code marker:\n%s", src)
	}
	for _, want := range []string{
		"Copyright 2015 Mozilla", "LICENSE-pdfjs", pdfjsCommit,
		"var pdfjsStandardFontGlyphs = map[uint16]rune{", "var pdfjsCalibriGlyphs = map[uint16]rune{",
		"1004: 0x0030, // 0",
		"var pdfjsArialBlackGlyphs = map[uint16]rune{",
		"var pdfjsStdFontMap = map[string]string{", `"Times-Roman": "Times-Roman",`,
		`"MS-Gothic": "MS Gothic",`, "var pdfjsSerifFonts = map[string]bool{", `"Adobe Jenson": true,`,
		"var pdfjsSymbolsFonts = map[string]bool{",
	} {
		if !strings.Contains(src, want) {
			t.Errorf("output lacks %q", want)
		}
	}
	if _, err := parser.ParseFile(token.NewFileSet(), "pdfjs_glyphs.go", code, parser.ParseComments); err != nil {
		t.Errorf("output does not parse: %v", err)
	}

	if _, err := generate(strings.Replace(sampleJS, "Mozilla Foundation", "Someone", 1)); !errors.Is(err, errNoCopyright) {
		t.Errorf("source without the Mozilla copyright: err = %v, want %v", err, errNoCopyright)
	}
}

func TestParseNameTable(t *testing.T) {
	t.Parallel()

	got, err := parseNameTable(sampleJS, "getNonStdFontMap", false)
	if err != nil || len(got) != 2 || got["Calibri"] != "Helvetica" || got["MS-Gothic"] != "MS Gothic" {
		t.Errorf("getNonStdFontMap = %v (err %v)", got, err)
	}
	flags, err := parseNameTable(sampleJS, "getSerifFonts", true)
	if _, ok := flags["Adobe Jenson"]; err != nil || len(flags) != 2 || !ok {
		t.Errorf("getSerifFonts = %v (err %v)", flags, err)
	}

	table := func(body string) string {
		return "const getX = getLookupTableFactory(function (t) {\n" + body + "\n});\n"
	}
	for _, tc := range []struct {
		desc string
		js   string
		flag bool
		want error
	}{
		{"absent", sampleJS, false, errTableNotFound},
		{"flag in a name table", table(`  t.Arial = true;`), false, errUnexpectedStmt},
		{"name in a flag table", table(`  t.Arial = "Helvetica";`), true, errUnexpectedStmt},
		{"computed value", table(`  t.Arial = t.Helvetica;`), false, errUnexpectedStmt},
		{"duplicate", table("  t.Arial = \"Helvetica\";\n  t[\"Arial\"] = \"Times-Roman\";"), false, errDuplicateName},
	} {
		if _, err := parseNameTable(tc.js, "getX", tc.flag); !errors.Is(err, tc.want) {
			t.Errorf("%s: err = %v, want %v", tc.desc, err, tc.want)
		}
	}
}

func TestComment(t *testing.T) {
	t.Parallel()

	got := comment(strings.Repeat("word ", 40))
	for line := range strings.SplitSeq(strings.TrimSuffix(got, "\n"), "\n") {
		if !strings.HasPrefix(line, "// ") || len(line) > commentWidth {
			t.Errorf("line %q is not a comment line within %d columns", line, commentWidth)
		}
	}
}
