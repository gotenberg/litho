// TestDecoderDecodesAValidImage pins the CGO path end to end: a real JPEG 2000
// stream must come back as exactly the pixels it encodes.
//
// Every other test here feeds the decoder garbage, which only proves it says
// no. This one proves libopenjp2 is actually driven correctly: the wrong
// component count, a wrong stride, or a mis-sized buffer all change the answer.
func TestDecoderDecodesAValidImage(t *testing.T) {
	t.Parallel()

	out, err := New().Decode(tinyJP2, nil)
	if err != nil {
		t.Fatalf("decoding a valid JPEG 2000 image: %v", err)
	}
	if len(out) != 64 {
		t.Fatalf("decoded %d bytes, want 64 (8x8, one component)", len(out))
	}
	for y := range 8 {
		for x := range 8 {
			want := byte((x*16 + y*2) % 256)
			if got := out[y*8+x]; got != want {
				t.Errorf("pixel (%d,%d) = %d, want %d", x, y, got, want)
			}
		}
	}
}
