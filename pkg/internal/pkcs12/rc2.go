// rc2Decrypter decrypts RC2 blocks (RFC 2268). It exists for the
// pbeWithSHAAnd40BitRC2-CBC and pbeWithSHAAnd128BitRC2-CBC schemes of old
// PKCS #12 stores and implements no encryption: litho never writes RC2.
type rc2Decrypter struct {
	k [64]uint16
}

// newRC2Decrypter expands key with effectiveBits effective key bits (RFC
// 2268, 2).
func newRC2Decrypter(key []byte, effectiveBits int) (*rc2Decrypter, error) {
	if len(key) < 1 || len(key) > 128 {
		return nil, fmt.Errorf("%w: RC2 key of %d bytes", ErrMalformed, len(key))
	}
	if effectiveBits < 1 || effectiveBits > 1024 {
		return nil, fmt.Errorf("%w: RC2 effective key length of %d bits", ErrMalformed, effectiveBits)
	}
	var l [128]byte
	copy(l[:], key)
	t := len(key)
	for i := t; i < 128; i++ {
		l[i] = rc2PiTable[l[i-1]+l[i-t]]
	}
	t8 := (effectiveBits + 7) / 8
	tm := byte(0xff >> (8*t8 - effectiveBits))
	l[128-t8] = rc2PiTable[l[128-t8]&tm]
	for i := 127 - t8; i >= 0; i-- {
		l[i] = rc2PiTable[l[i+1]^l[i+t8]]
	}
	c := &rc2Decrypter{}
	for i := range c.k {
		c.k[i] = uint16(l[2*i]) | uint16(l[2*i+1])<<8
	}
	return c, nil
}

// BlockSize returns the RC2 block size.
func (*rc2Decrypter) BlockSize() int { return rc2BlockSize }

// Decrypt decrypts the block src into dst, running the mixing and mashing
// rounds of RFC 2268, 3 backwards (RFC 2268, 4).
func (c *rc2Decrypter) Decrypt(dst, src []byte) {
	r := [4]uint16{
		binary.LittleEndian.Uint16(src[0:]),
		binary.LittleEndian.Uint16(src[2:]),
		binary.LittleEndian.Uint16(src[4:]),
		binary.LittleEndian.Uint16(src[6:]),
	}
	j := 63
	mix := func() {
		// RFC 2268, 4.1: the inverse of one mixing round, words 3 to 0.
		r[3] = bits.RotateLeft16(r[3], -5) - c.k[j] - (r[2] & r[1]) - (^r[2] & r[0])
		j--
		r[2] = bits.RotateLeft16(r[2], -3) - c.k[j] - (r[1] & r[0]) - (^r[1] & r[3])
		j--
		r[1] = bits.RotateLeft16(r[1], -2) - c.k[j] - (r[0] & r[3]) - (^r[0] & r[2])
		j--
		r[0] = bits.RotateLeft16(r[0], -1) - c.k[j] - (r[3] & r[2]) - (^r[3] & r[1])
		j--
	}
	mash := func() {
		// RFC 2268, 4.2: the inverse of one mashing round.
		r[3] -= c.k[r[2]&63]
		r[2] -= c.k[r[1]&63]
		r[1] -= c.k[r[0]&63]
		r[0] -= c.k[r[3]&63]
	}
	for range 5 {
		mix()
	}
	mash()
	for range 6 {
		mix()
	}
	mash()
	for range 5 {
		mix()
	}
	binary.LittleEndian.PutUint16(dst[0:], r[0])
	binary.LittleEndian.PutUint16(dst[2:], r[1])
	binary.LittleEndian.PutUint16(dst[4:], r[2])
	binary.LittleEndian.PutUint16(dst[6:], r[3])
}
