package document

import "testing"

// TestHeaderVersionReadsOnlyTheNumber pins that the version stops at the end of
// the number, not the end of the line.
//
// Per ISO 32000-1, 7.5.2 the header line is "%PDF-1.N" and the rest of the line
// is comment text. Reading to the line break reported pdfjs issue15033.pdf,
// whose header is "%PDF-1.3%", as version "1.3%": not a version, and it
// compares against nothing, so the catalog /Version precedence rule could not
// be applied to it either.
func TestHeaderVersionReadsOnlyTheNumber(t *testing.T) {
	t.Parallel()

	for _, tc := range []struct {
		name string
		buf  string
		want string
	}{
		{"plain", "1.4\n", "1.4"},
		{"carriage return", "1.7\r%\xe2\xe3\xcf\xd3\r\n", "1.7"},
		{"trailing comment character", "1.3%\r\n", "1.3"},
		{"trailing text", "1.5 generated by something\n", "1.5"},
		{"PDF 2.0", "2.0\n", "2.0"},
		{"two-digit minor", "1.10\n", "1.10"},
		{"no minor digit", "1.\n1 0 obj\n", ""},
		{"no period", "17\n", ""},
		{"not a number", "abc\n", ""},
		{"empty", "", ""},
		{"period only", ".\n", ""},
		{"number runs to the end of the buffer", "1.4", "1.4"},
	} {
		if got := headerVersion([]byte(tc.buf)); got != tc.want {
			t.Errorf("%s: headerVersion(%q) = %q, want %q", tc.name, tc.buf, got, tc.want)
		}
	}
}
