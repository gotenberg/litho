// TestLocales_EveryConstantHasData checks that every Locale constant of
// models names a locale of the table, that the table holds nothing else,
// that LocaleOf finds each tag back, and that each locale's identifier
// names a locale of the same language.
func TestLocales_EveryConstantHasData(t *testing.T) {
	fset := gotoken.NewFileSet()
	file, err := parser.ParseFile(fset, "../../models/locale_gen.go", nil, 0)
	if err != nil {
		t.Fatal(err)
	}
	consts := map[models.Locale]bool{}
	ast.Inspect(file, func(n ast.Node) bool {
		if lit, ok := n.(*ast.BasicLit); ok && lit.Kind == gotoken.STRING {
			v, err := strconv.Unquote(lit.Value)
			if err != nil {
				t.Fatal(err)
			}
			consts[models.Locale(v)] = true
		}
		return true
	})
	if len(consts) != len(locales) {
		t.Errorf("%d constants, %d locales", len(consts), len(locales))
	}
	for tag := range consts {
		d := lookup(tag)
		if d == nil {
			t.Errorf("%s: no data", tag)
			continue
		}
		if LocaleOf(string(tag)) != tag {
			t.Errorf("LocaleOf(%s) = %s", tag, LocaleOf(string(tag)))
		}
		if d.decimal == "" || d.group == "" || d.months[0][1] == "" || d.days[0][1] == "" || d.codes[CodeDate] == "" {
			t.Errorf("%s: missing fields", tag)
		}
		if back := localeOfLCID(uint64(d.lcid)); back == nil || lang(back.tag) != lang(tag) {
			t.Errorf("%s: identifier %x names %v", tag, d.lcid, back)
		}
	}
	for i := 1; i < len(locales); i++ {
		if locales[i-1].tag >= locales[i].tag {
			t.Errorf("locales not sorted at %s", locales[i].tag)
		}
	}
	for i := 1; i < len(lcidLocales); i++ {
		if lcidLocales[i-1].id >= lcidLocales[i].id {
			t.Errorf("identifiers not sorted at %x", lcidLocales[i].id)
		}
	}
}

// lang returns the language of a tag.
func lang(tag models.Locale) string {
	for i := range len(tag) {
		if tag[i] == '-' {
			return string(tag[:i])
		}
	}
	return string(tag)
}

// TestWithLocale_BooleanEquivalent checks that the code an ODS boolean
// style reads as writes the locale's words, as Calc writes a boolean style
// that names no language.
//
// # Corpus evidence
//
//   - probe, ods: a boolean style of no language prints true and false as
//     VRAI and FAUX under fr-FR, WAHR under de-DE, TRUE under en-US.
func TestWithLocale_BooleanEquivalent(t *testing.T) {
	f, err := Parse(`"TRUE";"TRUE";"FALSE"`)
	if err != nil {
		t.Fatal(err)
	}
	for _, tt := range []struct {
		loc  models.Locale
		v    float64
		want string
	}{{models.LocaleFrFR, 1, "VRAI"}, {models.LocaleFrFR, 0, "FAUX"}, {models.LocaleDeDE, 1, "WAHR"}, {"", 1, "TRUE"}} {
		if got := f.WithLocale(tt.loc).Apply(Value{Kind: Number, Number: tt.v}).Text; got != tt.want {
			t.Errorf("%s %v: %q, want %q", tt.loc, tt.v, got, tt.want)
		}
	}
}

// TestWithLocale_NumberInTextFormat checks that a number in a text format
// prints in the standard format with the locale's decimal separator, as
// Calc prints it.
//
// # Corpus evidence
//
//   - probe, xlsx: a cell of built-in format 49 (@) prints 1234.5 as
//     1234,5 under de-DE and 1234٫5 under ar-EG, and -1234.5 as -1234,5
//     under de-DE, in LibreOffice 26.8.2.2 of the pinned image.
func TestWithLocale_NumberInTextFormat(t *testing.T) {
	for _, tt := range []struct {
		loc  models.Locale
		v    float64
		want string
	}{
		{models.LocaleDeDE, 1234.5, "1234,5"},
		{models.LocaleDeDE, -1234.5, "-1234,5"},
		{models.LocaleArEG, 1234.5, "1234٫5"},
		{models.LocaleEnUS, 1234.5, "1234.5"},
	} {
		f, err := Parse("@")
		if err != nil {
			t.Fatal(err)
		}
		if got := f.WithLocale(tt.loc).Apply(Value{Kind: Number, Number: tt.v}).Text; got != tt.want {
			t.Errorf("%s %v: %q, want %q", tt.loc, tt.v, got, tt.want)
		}
	}
}
